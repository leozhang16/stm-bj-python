#!/bin/bash
# run_compile_test_mac.sh -- compile (and optionally run) the Igor procedures in
# Igor Pro 8 on this Mac, with DaqMxFunctions.xop replaced by MX_Stubs_for_compile_test.ipf.
#
#   tests/run_compile_test_mac.sh [folder] [--setup Setup_NewDAQ_STMBJ] [--run "IgorCommand"]... [--keep]
#
# folder   : the folder holding the .ipf files (default: parent of this script)
# --setup  : the top-level include file, without .ipf (default Setup_NewDAQ_STMBJ)
# --run    : an Igor command to execute after a successful compile (repeatable);
#            its error text, if any, is printed. Use to smoke-test functions.
# --keep   : leave Igor running afterwards (default: quit it)
#
# How it works: Igor is (re)started, then driven over AppleScript "do script".
# The operation queue inserts #include lines for the stubs, a generated marker
# file and the setup file, compiles, and runs ClaudeCompileMarker(), which writes
# tests/_generated/compile_result.txt. If that file does not appear, the compile
# failed; Igor leaves the offending line selected in the front procedure window,
# which we read back (window name + line) through a second command.
#
# Exit code: 0 compiled (and every --run command returned "No Error"), 1 otherwise.
set -u

HERE="$(cd "$(dirname "$0")" && pwd)"
FOLDER="$(cd "$HERE/.." && pwd)"
SETUP="Setup_NewDAQ_STMBJ"
STUBS="MX_Stubs_for_compile_test"      # --stubs MX_Sim_for_test | none
EXTRA=()                               # --include <name in tests/> (repeatable)
KEEP=0
RUNS=()
while [ $# -gt 0 ]; do
  case "$1" in
    --setup) SETUP="$2"; shift 2;;
    --stubs) STUBS="$2"; shift 2;;
    --include) EXTRA+=("$2"); shift 2;;
    --smoke) SMOKE=1; shift;;          # simulator + both smoke passes, result paths generated here
    --run) RUNS+=("$2"); shift 2;;
    --keep) KEEP=1; shift;;
    -h|--help) sed -n 2,20p "$0"; exit 0;;
    *) FOLDER="$(cd "$1" && pwd)"; shift;;
  esac
done

IGOR_APP="/Applications/Igor Pro 8 Folder/Igor64.app"
VOL="$(diskutil info / 2>/dev/null | awk -F': *' '/Volume Name/{print $2}')"
VOL="${VOL:-Macintosh HD}"
posix2mac() { echo "${VOL}$(echo "$1" | sed 's#/#:#g')"; }

GEN="$HERE/_generated"
mkdir -p "$GEN"
RESULT="$GEN/compile_result.txt"
ERRLOC="$GEN/compile_errloc.txt"
rm -f "$RESULT" "$ERRLOC"

MAC_FOLDER="$(posix2mac "$FOLDER")"
MAC_HERE="$(posix2mac "$HERE")"
MAC_GEN="$(posix2mac "$GEN")"

if [ "${SMOKE:-0}" = 1 ]; then
  STUBS="MX_Sim_for_test"
  EXTRA+=("Smoke_NewDAQ")
  RUNS+=("ClaudeSmokeRun(\"$MAC_GEN:smoke_result.txt\")" "ClaudeSmokeRun2(\"$MAC_GEN:smoke_result2.txt\")")
  RUN_TIMEOUT=${RUN_TIMEOUT:-600}
  rm -f "$GEN/smoke_result.txt" "$GEN/smoke_result2.txt"
fi

# The marker procedure, generated so it carries this machine's absolute path.
cat > "$GEN/CompileTest_Marker.ipf" <<EOF
#pragma TextEncoding = "UTF-8"
#pragma rtGlobals=3
// Generated by run_compile_test_mac.sh -- compile-test only, do not ship.
Function ClaudeCompileMarker()
	Variable refnum
	Open refnum as "$MAC_GEN:compile_result.txt"
	fprintf refnum, "COMPILED OK\r"
	fprintf refnum, "Igor: %s\r", IgorInfo(0)
	fprintf refnum, "user functions compiled: %d\r", ItemsInList(FunctionList("*",";",""))
	fprintf refnum, "InitializeExperiment exists: %d (6 = user function)\r", exists("InitializeExperiment")
	fprintf refnum, "HighResCardApproach exists: %d\r", exists("HighResCardApproach")
	fprintf refnum, "Keithley SetUpGPIB_Keithley exists: %d (0 expected)\r", exists("SetUpGPIB_Keithley")
	fprintf refnum, "Actuator StepActuatorCloser exists: %d (0 expected)\r", exists("StepActuatorCloser")
	fprintf refnum, "Window macros: %s\r", WinList("*",";","WIN:128")
	Close refnum
	return 0
End
EOF

IGOR_TIMEOUT=${IGOR_TIMEOUT:-60}        # seconds to wait for one "do script" reply (long --run commands need more)
igor() {  # igor "<Igor command line>"  -> prints Igor's reply ("No Error" or an error string)
  local cmd="$1"
  # escape for an AppleScript string literal: backslash and double quote
  cmd="${cmd//\\/\\\\}"; cmd="${cmd//\"/\\\"}"
  # AppleScript itself gives up after 2 minutes unless told otherwise, hence "with timeout"
  timeout "$IGOR_TIMEOUT" osascript -e "with timeout of $IGOR_TIMEOUT seconds" -e "tell application \"Igor64\" to do script \"$cmd\"" -e "end timeout" 2>&1
}

echo "== Igor compile test =="
echo "folder : $FOLDER"
echo "setup  : $SETUP.ipf"
if pgrep -x Igor64 >/dev/null; then pkill -x Igor64; sleep 3; fi
open -a "$IGOR_APP" || { echo "cannot launch Igor"; exit 1; }
ready=0
for i in $(seq 1 40); do
  sleep 2
  if igor 'Print 1' | grep -q "No Error"; then ready=1; break; fi
done
[ $ready = 1 ] || { echo "Igor did not become ready"; exit 1; }
echo "Igor is up."

# Queue: include stubs (or the simulator), extra test files, marker, setup; compile; run marker.
Q=""
if [ "$STUBS" != "none" ]; then Q="$Q Execute/P \"INSERTINCLUDE \\\"$MAC_HERE:$STUBS\\\"\";"; fi
for x in ${EXTRA[@]+"${EXTRA[@]}"}; do Q="$Q Execute/P \"INSERTINCLUDE \\\"$MAC_HERE:$x\\\"\";"; done   # bash 3.2 + set -u safe
Q="$Q Execute/P \"INSERTINCLUDE \\\"$MAC_GEN:CompileTest_Marker\\\"\"; Execute/P \"INSERTINCLUDE \\\"$MAC_FOLDER:$SETUP\\\"\"; Execute/P \"COMPILEPROCEDURES \"; Execute/P \"ClaudeCompileMarker()\""
echo "stubs  : $STUBS  extra: ${EXTRA[*]-none}"
igor "$Q" >/dev/null

ok=0
for i in $(seq 1 30); do
  sleep 1
  if [ -f "$RESULT" ]; then ok=1; break; fi
done

if [ $ok = 1 ]; then
  echo "== COMPILE: PASS =="
  tr '\r' '\n' < "$RESULT"
else
  echo "== COMPILE: FAIL =="
  # Igor selects the offending token in the procedure window that holds the error
  # and brings that window to the front. Dump the front window first, then every
  # procedure window's selection (a fresh window sits at paragraph 0, column 0).
  WINS="$GEN/compile_windows.txt"; rm -f "$WINS"
  igor "Variable/G gClaudeRef; Open gClaudeRef as \"$MAC_GEN:compile_windows.txt\"; fprintf gClaudeRef, \"%s\\r%s\\r\", WinName(0,128), WinList(\"*\",\";\",\"WIN:128\"); Close gClaudeRef" >/dev/null
  sleep 1
  front="$(tr '\r' '\n' < "$WINS" 2>/dev/null | sed -n 1p)"
  list="$(tr '\r' '\n' < "$WINS" 2>/dev/null | sed -n 2p)"
  echo "front procedure window: $front"
  echo "procedure windows     : $list"
  : > "$ERRLOC"
  IFS=';' read -ra WARR <<< "$list"
  for w in "${WARR[@]}"; do
    [ -z "$w" ] && continue
    # window names carry ".ipf", so they must be passed as $"name"
    igor "GetSelection procedure, \$\"$w\", 1; Variable/G gClaudeRef; Open/A gClaudeRef as \"$MAC_GEN:compile_errloc.txt\"; fprintf gClaudeRef, \"%s|%d|%d\\r\", \"$w\", V_startParagraph, V_startPos; Close gClaudeRef" >/dev/null
  done
  sleep 1
  found=0
  while IFS='|' read -r win para pos; do
    [ -z "$win" ] && continue
    if [ "$win" = "$front" ] || [ "$para" != "0" ] || [ "$pos" != "0" ]; then
      line=$((para + 1))
      echo "error candidate: $win line $line (column $pos)$( [ "$win" = "$front" ] && echo '  <- front window')"
      src=""
      for cand in "$FOLDER/$win" "$HERE/$win" "$GEN/$win"; do [ -f "$cand" ] && src="$cand" && break; done
      if [ -n "$src" ]; then
        awk -v L="$line" 'NR>=L-3 && NR<=L+3 {printf "%s%5d\t%s\n", (NR==L?">>":"  "), NR, $0}' "$src" | sed 's/\r$//'
      else
        echo "  (window '$win' is not a file in the folder; 'Procedure' is the experiment's own procedure window)"
      fi
      found=1
    fi
  done < <(tr '\r' '\n' < "$ERRLOC")
  if [ $found = 0 ]; then
    echo "(no window has a selection: Igor probably stopped before compiling, e.g. a text-encoding or include dialog)"
  fi
  igor "Variable/G gClaudeRef; Open gClaudeRef as \"$MAC_GEN:compile_state.txt\"; fprintf gClaudeRef, \"%s\\r\", FunctionList(\"InitializeExperiment\",\";\",\"\"); Close gClaudeRef" >/dev/null
  sleep 1
  echo "FunctionList says    : $(tr '\r' '\n' < "$GEN/compile_state.txt" 2>/dev/null | sed -n 1p)"
fi

rc=$(( ok == 1 ? 0 : 1 ))
NRUNS=${RUNS[@]+${#RUNS[@]}}; NRUNS=${NRUNS:-0}     # bash 3.2 + set -u safe count
if [ $ok = 1 ] && [ "$NRUNS" -gt 0 ]; then
  echo "== RUN commands (reply timeout ${RUN_TIMEOUT:-900} s each) =="
  for r in ${RUNS[@]+"${RUNS[@]}"}; do
    reply="$(IGOR_TIMEOUT=${RUN_TIMEOUT:-900} igor "$r")"
    [ -z "$reply" ] && reply="(empty reply: the command timed out, or Igor showed a dialog -- a runtime error or Abort)"
    printf '%s\n  -> %s\n' "$r" "$reply"
    echo "$reply" | grep -q "No Error" || rc=1
  done
fi

if [ "${SMOKE:-0}" = 1 ]; then
  for r in smoke_result.txt smoke_result2.txt; do
    if [ -f "$GEN/$r" ]; then
      p=$(tr '\r' '\n' < "$GEN/$r" | grep -c '^PASS'); f=$(tr '\r' '\n' < "$GEN/$r" | grep -c '^FAIL')
      echo "== $r: $p PASS, $f FAIL =="; tr '\r' '\n' < "$GEN/$r" | grep '^FAIL'
      [ "$f" = 0 ] || rc=1
    else
      echo "== $r: missing (the run did not finish) =="; rc=1
    fi
  done
fi
if [ $KEEP = 0 ]; then pkill -x Igor64; fi
exit $rc
